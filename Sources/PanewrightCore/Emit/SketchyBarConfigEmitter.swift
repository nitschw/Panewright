              ARGS+=(--set w.disk drawing=off)
            fi

            if on battery; then
            BINFO=$(pmset -g batt 2>/dev/null | tail -1)
            BPCT=$(printf '%s' "$BINFO" | grep -oE '[0-9]+%' | head -1)
            BREM=$(printf '%s' "$BINFO" | grep -oE '[0-9]+:[0-9]+' | head -1)
            case "$BINFO" in *charging*) BSYM="⚡";; *) BSYM="";; esac
            ARGS+=(--set w.batt drawing=on label="${BSYM}${BPCT:-?}${BREM:+ · $BREM}")
            else
              ARGS+=(--set w.batt drawing=off)
            fi

            if on docker; then
            if command -v docker >/dev/null 2>&1; then
              DC=$(docker ps -q 2>/dev/null | grep -c .)
              ARGS+=(--set w.docker drawing=on label="⬢ $DC")
            else
              ARGS+=(--set w.docker drawing=off)
            fi
            else
              ARGS+=(--set w.docker drawing=off)
            fi

            if on cloud-context; then
            # Highlight anything that looks like production — this widget's
            # whole point is catching "wait, which cluster am I on?".
            CTX=""
            command -v kubectl >/dev/null 2>&1 && CTX=$(kubectl config current-context 2>/dev/null)
            [ -n "$AWS_PROFILE" ] && CTX="${CTX:+$CTX · }aws:$AWS_PROFILE"
            if [ -n "$CTX" ]; then
              case "$CTX" in *prod*|*production*) CCOL=\(accent);; *) CCOL=\(palette.dim);; esac
              ARGS+=(--set w.cloud drawing=on label="$CTX" label.color=$CCOL)
            else
              ARGS+=(--set w.cloud drawing=off)
            fi
            else
              ARGS+=(--set w.cloud drawing=off)
            fi



            if on scratchpad; then
            SC=$("$A" list-windows --workspace S --format '%{window-id}' 2>/dev/null | grep -c .)
            if [ "${SC:-0}" -gt 0 ]; then
              ARGS+=(--set w.scratch drawing=on label="⇩ $SC")
            else
              ARGS+=(--set w.scratch drawing=off)
            fi
            else
              ARGS+=(--set w.scratch drawing=off)
            fi

            if on mic-mute; then
            MIC=$(osascript -e 'input volume of (get volume settings)' 2>/dev/null)
            if [ "${MIC:-0}" -eq 0 ] 2>/dev/null; then
              ARGS+=(--set w.mic drawing=on label="🎤⃠" label.color=\(accent))
            else
              ARGS+=(--set w.mic drawing=on label="🎤" label.color=\(palette.dim))
            fi
            else
              ARGS+=(--set w.mic drawing=off)
            fi

            if on volume; then
            VOL=$(osascript -e 'output volume of (get volume settings)' 2>/dev/null)
            MUTED=$(osascript -e 'output muted of (get volume settings)' 2>/dev/null)
            if [ "$MUTED" = "true" ]; then VSYM="🔇"; else VSYM="🔊"; fi
            ARGS+=(--set w.vol drawing=on label="$VSYM ${VOL:-0}%")
            else
              ARGS+=(--set w.vol drawing=off)
            fi

            if on brew-updates; then
            # brew outdated is slow, so cache it and refresh at most hourly.
            BREWC="$HOME/.config/panewright/.brew-outdated"
            # The app refreshes this cache hourly. Running `brew` here instead
            # returned 0: SketchyBar's spawn environment makes brew produce
            # nothing, though the identical command works in a normal shell.
            BREWN=$(cat "$BREWC" 2>/dev/null | tr -dc '0-9')
            if [ "${BREWN:-0}" -gt 0 ] 2>/dev/null; then
              ARGS+=(--set w.brew drawing=on label="⬆ ${BREWN}" label.color=\(accent))
            else
              ARGS+=(--set w.brew drawing=off)
            fi
            else
              ARGS+=(--set w.brew drawing=off)
            fi

            if on vpn; then
            # A utun with a peer address means a tunnel is actually carrying
            # traffic; macOS keeps empty utun interfaces around regardless.
            if ifconfig 2>/dev/null | awk '/^utun/{i=$1} /inet .*-->/{if(i)print i}' | grep -q .; then
              ARGS+=(--set w.vpn drawing=on label="VPN" label.color=\(accent))
            else
              ARGS+=(--set w.vpn drawing=off)
            fi
            else
              ARGS+=(--set w.vpn drawing=off)
            fi

            if on keyboard-layout; then
            KBD=$(defaults read ~/Library/Preferences/com.apple.HIToolbox.plist AppleSelectedInputSources 2>/dev/null \\
              | awk -F'"' '/KeyboardLayout Name/{print $4; exit}')
            [ -n "$KBD" ] && ARGS+=(--set w.kbd drawing=on label="$KBD") \\
                          || ARGS+=(--set w.kbd drawing=off)
            else
              ARGS+=(--set w.kbd drawing=off)
            fi

            if on focus-mode; then
            FOCUS="$HOME/Library/DoNotDisturb/DB/Assertions.json"
            if [ -s "$FOCUS" ] && /usr/bin/python3 -c \\
              'import json,sys; d=json.load(open(sys.argv[1])); sys.exit(0 if d.get("data",[{}])[0].get("storeAssertionRecords") else 1)' \\
              "$FOCUS" 2>/dev/null; then
              ARGS+=(--set w.focus drawing=on label="🌙" label.color=\(accent))
            else
              ARGS+=(--set w.focus drawing=off)
            fi
            else
              ARGS+=(--set w.focus drawing=off)
            fi

            if on now-playing; then
            NP=""
            for APP in Spotify Music; do
              if pgrep -x "$APP" >/dev/null 2>&1; then
                STATE=$(osascript -e "tell application \\"$APP\\" to player state as string" 2>/dev/null)
                if [ "$STATE" = "playing" ]; then
                  NP=$(osascript -e "tell application \\"$APP\\" to (name of current track) & \\" — \\" & (artist of current track)" 2>/dev/null)
                  break
                fi
              fi
            done
            if [ -n "$NP" ]; then
              ARGS+=(--set w.play drawing=on label="♪ $(printf '%.28s' "$NP")")
            else
              ARGS+=(--set w.play drawing=off)
            fi
            else
              ARGS+=(--set w.play drawing=off)
            fi

            if on weather; then
            # One network call an hour, cached; the bar never blocks on it.
            WC="$HOME/.config/panewright/.weather"
            if [ ! -f "$WC" ] || [ $(( $(date +%s) - $(stat -f %m "$WC" 2>/dev/null || echo 0) )) -gt 3600 ]; then
              curl -sf --max-time 5 'https://wttr.in/?format=%c%t' -o "$WC.tmp" 2>/dev/null &&
                [ -s "$WC.tmp" ] && mv "$WC.tmp" "$WC"
            fi
            WX=$(cat "$WC" 2>/dev/null | tr -d '+' | head -c 20)
            [ -n "$WX" ] && ARGS+=(--set w.weather drawing=on label="$WX") \\
                         || ARGS+=(--set w.weather drawing=off)
            else
              ARGS+=(--set w.weather drawing=off)
            fi

            [ ${#ARGS[@]} -gt 0 ] && "$BAR" "${ARGS[@]}"
            exit 0
            """

        let reorderPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. Several plugins add right-side items
            # independently, and each reordering only its own items left the
            # groups interleaved — to-do pills drifting away from their "+"
            # button, widgets landing between them. This is the SINGLE ordering
            # authority for the whole right side: widgets (in the user's order,
            # graphs kept beside their chip), then to-dos with their + button,
            # then integrations.
            BAR="$(command -v sketchybar)"
            ORDERFILE="$HOME/.config/panewright/.widgets-order"
            LEFT=""
            for i in $(seq 0 9); do
              "$BAR" --query pill.$i >/dev/null 2>&1 && LEFT="$LEFT pill.$i"
            done
            if [ -n "$LEFT" ]; then
              "$BAR" --reorder \(spaceOrder) \\
                mode front_app $LEFT
            fi
            ORDER=""
            while read -r item; do
              [ -z "$item" ] && continue
              "$BAR" --query "$item" >/dev/null 2>&1 && ORDER="$ORDER $item"
            done < "$ORDERFILE" 2>/dev/null
            for i in $(seq 0 19); do
              "$BAR" --query todo.item.$i >/dev/null 2>&1 && ORDER="$ORDER todo.item.$i"
            done
            "$BAR" --query todo >/dev/null 2>&1 && ORDER="$ORDER todo"
            for i in $(seq 0 5); do
              "$BAR" --query integration.$i >/dev/null 2>&1 && ORDER="$ORDER integration.$i"
            done
            [ -n "$ORDER" ] && "$BAR" --reorder $ORDER
            """

        return Files(
            sketchybarrc: rc + "\n",
            workspacesPlugin: workspacesPlugin + "\n",
            modePlugin: modePlugin + "\n",
            frontAppPlugin: frontAppPlugin + "\n",
            todoPlugin: todoPlugin + "\n",
            integrationsPlugin: integrationsPlugin + "\n",
            reorderPlugin: reorderPlugin + "\n",
            pillsPlugin: pillsPlugin + "\n",
            systemPlugin: systemPlugin + "\n",
            widgetsPlugin: widgetsPlugin + "\n",
            tooltipPlugin: tooltipPlugin + "\n")
