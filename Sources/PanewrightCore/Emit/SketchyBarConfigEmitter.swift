/// Generates SketchyBar's config script and plugins from a PanewrightConfig.
/// Two aesthetics, one toggle: native (SF Pro, vibrancy, floating pill) and
/// technical (monospace, square, solid). The accent color follows the focus
/// border so the whole system reads as one theme.
public enum SketchyBarConfigEmitter {
    public struct Files: Equatable, Sendable {
        public var sketchybarrc: String
        public var workspacesPlugin: String
        public var modePlugin: String
        public var frontAppPlugin: String
        public var todoPlugin: String
        public var integrationsPlugin: String
        public var reorderPlugin: String
        public var pillsPlugin: String
        public var systemPlugin: String
        public var widgetsPlugin: String
        public var tooltipPlugin: String
    }

    private struct Palette {
        let barProps: String
        let font: String
        let text: String
        let dim: String
    }

    private static func palette(for theme: PanewrightConfig.StatusBar.Theme) -> Palette {
        switch theme {
        case .native:
            Palette(
                barProps:
                    "height=30 corner_radius=9 margin=8 y_offset=5 blur_radius=30 color=0x2c000000",
                font: "SF Pro:Semibold:13.0",
                text: "0xffffffff",
                dim: "0x80ffffff")
        case .technical:
            Palette(
                barProps:
                    "height=26 corner_radius=0 margin=0 y_offset=0 blur_radius=0 color=0xf016161e",
                font: "SF Mono:Bold:12.0",
                text: "0xffc0caf5",
                dim: "0x66c0caf5")
        }
    }

    /// Vertical space tiles must reserve so the bar isn't covered by windows:
    /// bar height + y-offset + breathing room. The AeroSpace emitter adds
    /// this to outer.top whenever the bar is enabled.
    public static func reservedTopGap(for theme: PanewrightConfig.StatusBar.Theme) -> Int {
        switch theme {
        case .native: 40  // height 30 + y_offset 5 + 5 breathing
        case .technical: 32  // height 26 + 6 breathing
        }
    }

    public static func emit(_ config: PanewrightConfig) throws -> Files {
        let accent = String(
            format: "0x%08x", try ColorHex.argb(fromCSSHex: config.focusBorder.activeColor))
        // The workspace highlight defaults to the border accent (one color, one
        // system) but can be set independently.
        let barAccent = try config.statusBar.accentColor.map {
            String(format: "0x%08x", try ColorHex.argb(fromCSSHex: $0))
        } ?? accent
        let palette = palette(for: config.statusBar.theme)
        let workspaces = AeroSpaceConfigEmitter.workspaceNumbers(in: config.bindings)
        let workspaceList = workspaces.map(String.init).joined(separator: " ")
        // Per-display item names, display outer so each monitor's strip stays
        // contiguous. Hidden items keep their slot but don't render. Each
        // display leads with its monitor badge (M1/M2/M3).
        let spaceOrder = (1...4)
            .flatMap { d in ["monitor.\(d)"] + workspaces.map { "space.\(d).\($0)" } }
            .joined(separator: " ")

        let rc = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright — do not edit by hand.
            # Edit panewright.toml (or use the Panewright app) instead.
            PLUGINS="$HOME/.config/sketchybar/plugins"
            SCRIPTS_DIR="$HOME/.config/panewright/scripts"
            BAR=/opt/homebrew/bin/sketchybar

            # Bottom bar: the top edge is the native menu bar's auto-reveal
            # zone, which fought our drag-to-park and workspace clicks. The
            # bottom edge triggers nothing, needs no menu-bar hiding, and is
            # consistent across a notched primary and flat externals.
            $BAR --bar position=bottom sticky=on \(palette.barProps)
            $BAR --default icon.font="\(palette.font)" label.font="\(palette.font)" \\
                icon.color=\(palette.text) label.color=\(palette.text) \\
                padding_left=4 padding_right=4

            $BAR --add event aerospace_workspace_change
            $BAR --add event panewright_mode
            $BAR --add event panewright_todo
            $BAR --add event panewright_integrations
            $BAR --add event panewright_pills
            $BAR --add event panewright_widgets

            \(config.pills.enabled ? """
            $BAR --add item pills left \\
              --set pills update_freq=90 drawing=off \\
                script="$PLUGINS/panewright_pills.sh" \\
              --subscribe pills panewright_pills
            """ : "")

            # One strip per display (associated_display). Each item shows only
            # when its workspace lives on that display's monitor. Displays
            # beyond the actual count never render. The M-badge leads each
            # strip, naming the AeroSpace monitor (the number monitor commands
            # refer to).
            for did in 1 2 3 4; do
              $BAR --add item monitor.$did left \\
                --set monitor.$did associated_display=$did label="" drawing=off \\
                  label.color=\(palette.dim) label.padding_left=8 label.padding_right=2
              for sid in \(workspaceList); do
                $BAR --add item space.$did.$sid left \\
                  --set space.$did.$sid associated_display=$did label="$sid" drawing=off \\
                    label.padding_left=8 label.padding_right=8 \\
                    background.corner_radius=6 background.height=20 background.drawing=off \\
                    click_script="$SCRIPTS_DIR/workspace-select.sh $did $sid"
              done
            done

            # A single hidden driver repaints every strip in one batched call.
            # Subscribing each pill individually would fork one process (and two
            # AeroSpace queries) per pill per event — a stampede that has
            # crashed SketchyBar. One process, one query per display instead.
            # update_freq keeps occupancy fresh (a window moved to a background
            # workspace) without an on-focus-changed trigger — focus changes
            # burst around system dialogs and the resulting concurrent repaints
            # crashed SketchyBar. Workspace switches still repaint instantly
            # via the event.
            $BAR --add item spaces_driver left \\
              --set spaces_driver drawing=off update_freq=2 \\
                script="$PLUGINS/panewright_workspaces.sh" \\
              --subscribe spaces_driver aerospace_workspace_change

            $BAR --add item mode left \\
              --set mode label="" label.color=\(accent) \\
                script="$PLUGINS/panewright_mode.sh" \\
              --subscribe mode panewright_mode

            $BAR --add item front_app left \\
              --set front_app script="$PLUGINS/panewright_front_app.sh" \\
              --subscribe front_app front_app_switched

            \(conflictsItem(count: BindingConflicts.rows(in: config).count))
            \(config.modules.systemMonitor ? systemItem(accent: accent, palette: palette) : "")
            \(widgetItems(config.modules, accent: accent, palette: palette))
            \(config.integrations.anyEnabled ? integrationsItem(accent: accent) : "")
            \(config.todo.enabled ? todoItem(accent: accent) : "")
            # Pin the order explicitly: without this, items can shuffle when
            # the bar re-renders (a screenshot or display change is enough).
            $BAR --reorder \(spaceOrder) mode front_app

            $BAR --update
            # AeroSpace may still be starting (any launch order must work) —
            # retry before painting the initial highlight.
            for attempt in $(seq 1 20); do
              FOCUSED="$(/opt/homebrew/bin/aerospace list-workspaces --focused 2>/dev/null)"
              [ -n "$FOCUSED" ] && break
              sleep 0.5
            done
            $BAR --trigger aerospace_workspace_change FOCUSED_WORKSPACE="$FOCUSED"
            \(config.todo.enabled ? "$BAR --trigger panewright_todo" : "")
            \(config.integrations.anyEnabled ? "$BAR --trigger panewright_integrations" : "")
            """

        let workspacesPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. Repaints every display's workspace strip
            # in ONE batched sketchybar call.
            #
            # i3-style dynamic pills: draw a workspace only when it lives on that
            # display's monitor AND is either occupied (has windows) or the one
            # currently visible there. Empty, unfocused workspaces vanish; moving
            # a window onto one makes its pill appear.
            BAR="$(command -v sketchybar)"
            A=/opt/homebrew/bin/aerospace
            MAP="$HOME/.config/panewright/monitor-map.tsv"
            ARGS=()
            for did in 1 2 3 4; do
              MON=$(awk -F'\\t' -v d="$did" '$1 == d { print $2 }' "$MAP" 2>/dev/null)
              # No map yet (first boot): assume identity for display 1 so a
              # single-monitor bar still renders before the app writes the map.
              [ -z "$MON" ] && [ ! -f "$MAP" ] && [ "$did" = 1 ] && MON=1
              if [ -z "$MON" ]; then
                ARGS+=(--set "monitor.$did" drawing=off)
                continue
              fi
              # Badge shows the human-facing number (col 3: primary is always
              # M1), while commands keep using the AeroSpace id (col 2).
              LBL=$(awk -F'\\t' -v d="$did" '$1 == d { print $3 }' "$MAP" 2>/dev/null)
              ARGS+=(--set "monitor.$did" drawing=on label="M${LBL:-$MON}")
              VISIBLE=$("$A" list-workspaces --monitor "$MON" --visible 2>/dev/null | tr -d ' ')
              OCCUPIED=$("$A" list-workspaces --monitor "$MON" --empty no 2>/dev/null | tr -d ' ')
              for sid in \(workspaceList); do
                if [ "$sid" = "$VISIBLE" ]; then
                  ARGS+=(--set "space.$did.$sid" drawing=on background.drawing=on \\
                    background.color=\(barAccent) label.color=0xffffffff)
                elif printf '%s\\n' "$OCCUPIED" | grep -qx "$sid"; then
                  ARGS+=(--set "space.$did.$sid" drawing=on background.drawing=off \\
                    label.color=\(palette.dim))
                else
                  ARGS+=(--set "space.$did.$sid" drawing=off)
                fi
              done
            done
            [ ${#ARGS[@]} -gt 0 ] && "$BAR" "${ARGS[@]}"
            """

        let modePlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. Badge for the active binding mode.
            if [ -z "$MODE" ] || [ "$MODE" = "main" ]; then
              "$(command -v sketchybar)" --set "$NAME" label=""
            else
              "$(command -v sketchybar)" --set "$NAME" label="[$(printf '%s' "$MODE" | tr '[:lower:]' '[:upper:]')]"
            fi
            """

        let frontAppPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright.
            "$(command -v sketchybar)" --set "$NAME" label="$INFO"
            """

        let todoPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. Renders the to-do item and its popup.
            BAR="$(command -v sketchybar)"
            SCRIPTS="$HOME/.config/panewright/scripts"
            PLUGINS_DIR="$HOME/.config/sketchybar/plugins"
            TODO="$HOME/.config/panewright/todo.txt"
            [ -f "$TODO" ] || touch "$TODO"

            # Storage is TSV: title<TAB>notes. Each task becomes its own pill
            # in the bar, growing leftward from the "+" button; click one to
            # open its editor.
            #
            # Incremental, not rebuild: removing and re-adding every pill on
            # each update made the whole bar flicker and visibly resort. Reuse
            # existing items (a --set repaints in place), add or remove only at
            # the tail, batch everything into ONE sketchybar call, and reorder
            # only when the item count actually changed.
            MAX=6
            EXISTING=$("$BAR" --query bar 2>/dev/null | /usr/bin/python3 -c \\
              'import sys,json;print(sum(1 for i in json.load(sys.stdin).get("items",[]) if i.startswith("todo.item.")))' 2>/dev/null)
            EXISTING=${EXISTING:-0}

            ARGS=()
            i=0
            while IFS= read -r line; do
              case "$line" in ""|" ") continue ;; esac
              [ "$i" -ge "$MAX" ] && break
              TITLE=$(printf '%s' "$line" | cut -f1)
              NOTES=$(printf '%s' "$line" | cut -f2- -s)
              SHORT=$(printf '%.18s' "$TITLE")
              [ "${#TITLE}" -gt 18 ] && SHORT="$SHORT…"
              [ -n "$NOTES" ] && SHORT="$SHORT ·"
              [ "$i" -ge "$EXISTING" ] && ARGS+=(--add item todo.item.$i right)
              ARGS+=(--set todo.item.$i label="$SHORT" label.color=\(palette.text) \\
                label.padding_left=8 label.padding_right=8 \\
                background.corner_radius=6 background.height=20 \\
                background.color=0x1affffff background.drawing=on \\
                click_script="$SCRIPTS/todo-edit.sh $((i + 1))")
              i=$((i + 1))
            done < "$TODO"
            j=$i
            while [ "$j" -lt "$EXISTING" ]; do
              ARGS+=(--remove todo.item.$j)
              j=$((j + 1))
            done

            # awk, not `grep -c || echo 0`: grep prints 0 *and* exits 1 when
            # nothing matches, which yields a two-line "count".
            TOTAL=$(awk 'NF' "$TODO" 2>/dev/null | wc -l | tr -d ' ')
            if [ "$TOTAL" -gt "$MAX" ]; then
              ARGS+=(--set todo label="+$((TOTAL - MAX)) more  +")
            else
              ARGS+=(--set todo label="+")
            fi
            [ ${#ARGS[@]} -gt 0 ] && "$BAR" "${ARGS[@]}"
            # One authority for right-side order — only when items came or went.
            [ "$i" -ne "$EXISTING" ] && "$PLUGINS_DIR/panewright_reorder.sh"
            exit 0
            """

        let integrationsPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. One pill per enabled service, fed by
            # the status file the app writes: id<TAB>count<TAB>label.
            BAR="$(command -v sketchybar)"
            PLUGINS_DIR="$HOME/.config/sketchybar/plugins"
            STATUS="$HOME/.config/panewright/integrations.status"
            [ -f "$STATUS" ] || exit 0

            # Incremental like the todo plugin: reuse items, one batched call,
            # reorder only when the pill count changed (see there for why).
            EXISTING=$("$BAR" --query bar 2>/dev/null | /usr/bin/python3 -c \\
              'import sys,json;print(sum(1 for i in json.load(sys.stdin).get("items",[]) if i.startswith("integration.")))' 2>/dev/null)
            EXISTING=${EXISTING:-0}
            ARGS=()
            i=0
            while IFS=$'\\t' read -r id count label; do
              [ -z "$id" ] && continue
              COLOR=\(palette.dim)
              [ "${count:-0}" -gt 0 ] 2>/dev/null && COLOR=\(accent)
              # Extra left padding on the first pill separates this group
              # from the to-do pills.
              PAD=8
              [ "$i" -eq 0 ] && PAD=20
              [ "$i" -ge "$EXISTING" ] && ARGS+=(--add item integration.$i right)
              ARGS+=(--set integration.$i label="$label ${count:-0}" label.color="$COLOR" \\
                label.padding_left=$PAD label.padding_right=8 \\
                background.corner_radius=6 background.height=20 \\
                background.color=0x1affffff background.drawing=on \\
                click_script="open 'panewright://integrations/$id'")
              i=$((i + 1))
            done < "$STATUS"
            j=$i
            while [ "$j" -lt "$EXISTING" ]; do
              ARGS+=(--remove integration.$j)
              j=$((j + 1))
            done
            [ ${#ARGS[@]} -gt 0 ] && "$BAR" "${ARGS[@]}"
            [ "$i" -ne "$EXISTING" ] && "$PLUGINS_DIR/panewright_reorder.sh"
            exit 0
            """

        let pillsPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. One pill per parked window; click to
            # peek at it, right-click to give it back to the tiling tree.
            BAR="$(command -v sketchybar)"
            A=/opt/homebrew/bin/aerospace
            SCRIPTS="$HOME/.config/panewright/scripts"
            PLUGINS_DIR="$HOME/.config/sketchybar/plugins"
            PILLS="$HOME/.config/panewright/pills.tsv"
            [ -f "$PILLS" ] || touch "$PILLS"

            # Incremental like the todo plugin: reuse items, one batched call,
            # reorder only when the pill count changed (see there for why).
            EXISTING=$("$BAR" --query bar 2>/dev/null | /usr/bin/python3 -c \\
              'import sys,json;print(sum(1 for i in json.load(sys.stdin).get("items",[]) if i.startswith("pill.")))' 2>/dev/null)
            EXISTING=${EXISTING:-0}
            LIVE=$("$A" list-windows --all --format '%{window-id}' 2>/dev/null | tr -d ' ')
            PARKED=$("$A" list-windows --workspace P --format '%{window-id}' 2>/dev/null | tr -d ' ')

            TMP=$(mktemp)
            ARGS=()
            i=0
            while IFS=$'\\t' read -r id app title; do
              [ -z "$id" ] && continue
              # Drop pills whose window has closed.
              printf '%s\\n' "$LIVE" | grep -qx "$id" || continue
              printf '%s\\t%s\\t%s\\n' "$id" "$app" "$title" >> "$TMP"
              [ "$i" -ge 10 ] && continue
              LABEL=$(printf '%.14s' "${app:-window}")
              if printf '%s\\n' "$PARKED" | grep -qx "$id"; then
                COLOR=\(palette.dim); MARK="▸"
              else
                COLOR=\(accent); MARK="▾"
              fi
              [ "$i" -ge "$EXISTING" ] && ARGS+=(--add item pill.$i left)
              ARGS+=(--set pill.$i label="$MARK $LABEL" label.color="$COLOR" \\
                label.padding_left=8 label.padding_right=8 \\
                background.corner_radius=6 background.height=20 \\
                background.color=0x1affffff background.drawing=on \\
                click_script="if [ \\"\\$BUTTON\\" = \\"right\\" ]; then $SCRIPTS/pill-release.sh $id; else $SCRIPTS/pill-toggle.sh $id; fi")
              i=$((i + 1))
            done < "$PILLS"
            mv "$TMP" "$PILLS"
            j=$i
            while [ "$j" -lt "$EXISTING" ]; do
              ARGS+=(--remove pill.$j)
              j=$((j + 1))
            done
            [ ${#ARGS[@]} -gt 0 ] && "$BAR" "${ARGS[@]}"
            [ "$i" -ne "$EXISTING" ] && "$PLUGINS_DIR/panewright_reorder.sh"
            exit 0
            """

        let systemPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. Polls CPU/memory, feeds the two graphs,
            # and fills the perf-panel popup. All no-sudo, no-SIP.
            BAR="$(command -v sketchybar)"
            ENABLED="$HOME/.config/panewright/.widgets-enabled"
            # Respect the runtime toggle like every other widget, so turning
            # this off in the picker hides it without rebuilding the bar.
            if ! grep -qx "system-monitor" "$ENABLED" 2>/dev/null; then
              "$BAR" --set sys drawing=off \\
                     --set sys.cpu.graph drawing=off --set sys.mem.graph drawing=off
              exit 0
            fi
            "$BAR" --set sys drawing=on

            # CPU: top's second sample is the accurate instantaneous one.
            IDLE=$(top -l 2 -n 0 -s 1 2>/dev/null | awk '/CPU usage/{i=$7} END{gsub("%","",i); print i}')
            [ -z "$IDLE" ] && IDLE=100
            CPU=$(awk -v i="$IDLE" 'BEGIN{printf "%.0f", 100 - i}')

            # Memory: used physical vs. hardware total.
            TOTAL=$(sysctl -n hw.memsize 2>/dev/null)
            PAGE=$(sysctl -n hw.pagesize 2>/dev/null)
            USEDP=$(vm_stat 2>/dev/null | awk -v p="$PAGE" '
              /Pages active/{a=$3} /Pages wired/{w=$4} /Pages occupied by compressor/{c=$5}
              END{gsub("\\\\.","",a); gsub("\\\\.","",w); gsub("\\\\.","",c); print (a+w+c)*p}')
            MEM=$(awk -v u="$USEDP" -v t="$TOTAL" 'BEGIN{ if(t>0) printf "%.0f", u/t*100; else print 0 }')
            USEDG=$(awk -v u="$USEDP" 'BEGIN{printf "%.1f", u/1073741824}')
            TOTG=$(awk -v t="$TOTAL" 'BEGIN{printf "%.0f", t/1073741824}')

            # Feed the sparklines (0..1) and update the chip.
            # The graphs follow their own toggle, read at runtime like the
            # other widgets, so flipping them never rebuilds the bar.
            if grep -qx "system-graphs" "$HOME/.config/panewright/.widgets-enabled" 2>/dev/null; then
              GRAPHS=(--set sys.cpu.graph drawing=on --set sys.mem.graph drawing=on)
            else
              GRAPHS=(--set sys.cpu.graph drawing=off --set sys.mem.graph drawing=off)
            fi
            "$BAR" --push sys.cpu.graph "$(awk -v c="$CPU" 'BEGIN{print c/100}')" \\
                   --push sys.mem.graph "$(awk -v m="$MEM" 'BEGIN{print m/100}')" \\
                   "${GRAPHS[@]}" \\
                   --set sys label="CPU ${CPU}%  MEM ${MEM}%"

            # Only compute the panel body when it's actually open.
            OPEN=$("$BAR" --query sys 2>/dev/null | /usr/bin/python3 -c \\
              'import sys,json; print(json.load(sys.stdin).get("popup",{}).get("drawing",""))' 2>/dev/null)
            [ "$OPEN" != "on" ] && exit 0

            LOAD=$(sysctl -n vm.loadavg 2>/dev/null | tr -d '{}' | awk '{printf "%s %s %s", $1,$2,$3}')
            UP=$(uptime | sed -E 's/.*up ([^,]*),.*/\\1/' | xargs)
            ARGS=(--set sys.pop.load label="load $LOAD   ·   up $UP")
            ARGS+=(--set sys.pop.mem label="mem ${USEDG}G / ${TOTG}G used")
            # Top 5 by CPU, then by memory.
            i=1
            while read -r pid pct comm; do
              [ -z "$pid" ] && continue
              ARGS+=(--set sys.pop.cpu.$i label="$(printf '%-16.16s %5s%%' "$comm" "$pct")")
              i=$((i+1)); [ "$i" -gt 5 ] && break
            done < <(ps -Aro pid=,pcpu=,comm= 2>/dev/null | awk '{c=$3; for(j=4;j<=NF;j++) c=c" "$j; sub(".*/","",c); print $1, $2, c}' | head -5)
            i=1
            while read -r pid pct comm; do
              [ -z "$pid" ] && continue
              ARGS+=(--set sys.pop.mem.$i label="$(printf '%-16.16s %5s%%' "$comm" "$pct")")
              i=$((i+1)); [ "$i" -gt 5 ] && break
            done < <(ps -Amo pid=,pmem=,comm= 2>/dev/null | awk '{c=$3; for(j=4;j<=NF;j++) c=c" "$j; sub(".*/","",c); print $1, $2, c}' | head -5)
            "$BAR" "${ARGS[@]}"
            """

        let tooltipPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. Hover a widget for HOLD seconds and its
            # popup (the widget's name, or its detail panel) appears; leaving
            # hides it again. A token file makes the delayed reveal cancelable,
            # so passing the cursor over a chip never flashes a tooltip.
            BAR="$(command -v sketchybar)"
            STATE="$HOME/.config/panewright/.tooltip"
            HOLD=3
            case "$SENDER" in
              mouse.entered)
                TOKEN="$NAME.$RANDOM$RANDOM"
                printf '%s' "$TOKEN" > "$STATE"
                (
                  sleep "$HOLD"
                  # Only reveal if this hover is still the current one.
                  [ "$(cat "$STATE" 2>/dev/null)" = "$TOKEN" ] &&
                    "$BAR" --set "$NAME" popup.drawing=on
                ) >/dev/null 2>&1 &
                ;;
              mouse.exited)
                : > "$STATE"
                "$BAR" --set "$NAME" popup.drawing=off
                ;;
            esac
            exit 0
            """

        let m = config.modules
        let widgetsPlugin = """
            #!/bin/bash
            export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
            # Generated by Panewright. Refreshes every enabled widget in ONE
            # batched sketchybar call — one process per cycle, not one per
            # widget. All data is no-sudo, no-SIP.
            BAR="$(command -v sketchybar)"
            A=/opt/homebrew/bin/aerospace
            STATE="$HOME/.config/panewright/.widget-state"
            # Which widgets are on is read at RUNTIME from this file, not baked
            # into the script — so toggling one is a config write plus a
            # trigger, never a bar reload (which visibly tore the bar down).
            ENABLED="$HOME/.config/panewright/.widgets-enabled"
            on() { grep -qx "$1" "$ENABLED" 2>/dev/null; }
            ARGS=()

            if on network; then
            # Throughput from interface byte counters vs. the last cycle.
            IFACE=$(route -n get default 2>/dev/null | awk '/interface:/{print $2}')
            read -r RX TX <<<"$(netstat -ib 2>/dev/null | awk -v i="$IFACE" '$1==i && $7 ~ /^[0-9]+$/ {print $7, $10; exit}')"
            NOW=$(date +%s)
            if [ -f "$STATE" ]; then read -r PRX PTX PT < "$STATE"; else PRX=$RX; PTX=$TX; PT=$((NOW-1)); fi
            printf '%s %s %s\\n' "${RX:-0}" "${TX:-0}" "$NOW" > "$STATE"
            DT=$((NOW - PT)); [ "$DT" -lt 1 ] && DT=1
            human() { awk -v b="$1" 'BEGIN{ if(b>1048576) printf "%.1fM", b/1048576; else if(b>1024) printf "%.0fK", b/1024; else printf "%dB", b }'; }
            DOWN=$(human $(( (${RX:-0} - ${PRX:-0}) / DT )))
            UP=$(human $(( (${TX:-0} - ${PTX:-0}) / DT )))
            ARGS+=(--set w.net drawing=on label="↓$DOWN ↑$UP")
            else
              ARGS+=(--set w.net drawing=off)
            fi

            if on ports; then
            PORTS=$(lsof -iTCP -sTCP:LISTEN -P -n 2>/dev/null | awk 'NR>1{split($9,a,":"); print a[length(a)], $1}' | sort -un | head -8)
            COUNT=$(printf '%s\\n' "$PORTS" | grep -c . )
