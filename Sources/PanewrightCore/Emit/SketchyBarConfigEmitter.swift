    /// Every opt-in widget's bar item, plus the single hidden driver that
    /// refreshes them all. One driver — not one poller per widget — keeps this
    /// to a single process per cycle and one batched `--set`.
    private static func widgetItems(
        _ modules: PanewrightConfig.Modules, accent: String, palette: Palette
    ) -> String {
        var lines: [String] = []
        // Hovering a widget for a beat names it — these chips are terse by
        // design, so the tooltip is how you learn what "⇄ 8" means.
        func tooltip(_ name: String, _ text: String) -> String {
            """
            $BAR --set \(name) popup.background.corner_radius=8 \
            popup.background.border_width=1 popup.background.color=0xf01a1a22 \
            popup.background.border_color=0x44ffffff popup.horizontal=off \
            popup.align=right popup.y_offset=-6 script="$PLUGINS/panewright_tooltip.sh" \
            --add item \(name).tip popup.\(name) \
            --set \(name).tip label="\(text)" label.font="\(palette.font)" \
            label.color=\(palette.dim) label.padding_left=10 label.padding_right=10 \
            --subscribe \(name) mouse.entered mouse.exited
            """
        }
        /// `key` is the config key, so right-click can turn the widget off.
        func chip(_ name: String, _ key: String, _ tip: String, click: String? = nil) {
            // Right-click always disables; left-click runs the widget's own
            // action when it has one.
            let disable = "open 'panewright://widgets/disable/\(key)'"
            let action =
                click.map { "if [ \\\"$BUTTON\\\" = \\\"right\\\" ]; then \(disable); else \($0); fi" }
                ?? "if [ \\\"$BUTTON\\\" = \\\"right\\\" ]; then \(disable); fi"
            lines.append(
                "$BAR --add item \(name) right --set \(name) label=\"…\" drawing=off"
                    + " label.font=\"\(palette.font)\" label.padding_left=8 label.padding_right=8"
                    + " background.corner_radius=6 background.height=20"
                    + " click_script=\"\(action)\"")
            lines.append(tooltip(name, tip))
        }
        /// Ports already unfurls a list on click, so its popup leads with a
        /// title row that doubles as the hover tooltip.
        func portsChip() {
            let disable = "open 'panewright://widgets/disable/ports'"
            lines.append(
                "$BAR --add item w.ports right --set w.ports label=\"…\" drawing=off"
                    + " label.font=\"\(palette.font)\" label.padding_left=8 label.padding_right=8"
                    + " background.corner_radius=6 background.height=20"
                    + " popup.background.corner_radius=8 popup.background.border_width=1"
                    + " popup.background.color=0xf01a1a22 popup.background.border_color=0x44ffffff"
                    + " popup.horizontal=off popup.align=right popup.y_offset=-6"
                    + " script=\"$PLUGINS/panewright_tooltip.sh\""
                    + " click_script=\"if [ \\\\\\\"$BUTTON\\\\\\\" = \\\\\\\"right\\\\\\\" ]; then \(disable);"
                    + " else $BAR --set w.ports popup.drawing=toggle; fi\"")
            lines.append(
                "$BAR --add item w.ports.tip popup.w.ports --set w.ports.tip"
                    + " label=\"Listening ports\" label.font=\"\(palette.font)\""
                    + " label.color=\(accent) label.padding_left=10 label.padding_right=10")
            for i in 1...8 {
                lines.append(
                    "$BAR --add item w.ports.\(i) popup.w.ports --set w.ports.\(i) label=\"…\""
                        + " label.font=\"\(palette.font)\" label.padding_left=10"
                        + " label.padding_right=10 label.color=\(palette.dim)")
            }
            lines.append("$BAR --subscribe w.ports mouse.entered mouse.exited")
        }
        // Emitted in the user's configured order. SketchyBar stacks `right`
        // items leftward, so the list is reversed: the first configured widget
        // ends up leftmost, matching what the picker shows top to bottom.
        let specs: [String: (item: String, tip: String, click: String?)] = [
            "weather": ("w.weather", "Weather · current conditions", nil),
            "now-playing": (
                "w.play", "Now playing · click to play/pause",
                "osascript -e 'tell application \\\"Spotify\\\" to playpause' 2>/dev/null || osascript -e 'tell application \\\"Music\\\" to playpause'"),
            "focus-mode": ("w.focus", "Focus · Do Not Disturb state", nil),
            "keyboard-layout": ("w.kbd", "Keyboard · input source", nil),
            "vpn": ("w.vpn", "VPN · tunnel status", nil),
            "brew-updates": ("w.brew", "Homebrew · outdated packages", "open -a Terminal"),
            "volume": (
                "w.vol", "Volume · click to mute",
                "osascript -e 'set volume output muted (not (output muted of (get volume settings)))'"),
            "mic-mute": ("w.mic", "Microphone · click to toggle mute", "$SCRIPTS_DIR/mic-toggle.sh"),
            "scratchpad": ("w.scratch", "Scratchpad · stashed windows", nil),
            "cloud-context": ("w.cloud", "kubectl context / AWS profile", nil),
            "docker": ("w.docker", "Docker · running containers", nil),
            "battery": ("w.batt", "Battery · charge and time left", nil),
            "disk": ("w.disk", "Disk · boot volume", nil),
            "network": ("w.net", "Network · down / up per second", nil),
        ]
        for key in modules.resolvedOrder.reversed() {
            if key == "ports" {
                portsChip()
            } else if let spec = specs[key] {
                chip(spec.item, key, spec.tip, click: spec.click)
            }
        }
        lines.append(
            "$BAR --add item widgets_driver right --set widgets_driver drawing=off"
                + " update_freq=5 script=\"$PLUGINS/panewright_widgets.sh\""
                + " --subscribe widgets_driver panewright_widgets")
        return lines.joined(separator: "\n")
    }

    /// The system-monitor module: two live sparkline graphs (CPU, memory) and
    /// a chip that unfurls a mini-htop perf panel on click. All items are
    /// created once here; the plugin only `--set`s labels and `--push`es graph
    /// values, so nothing is added/removed at runtime (no flicker, no churn).
    private static func systemItem(accent: String, palette: Palette) -> String {
        // Popup rows are created once, relabeled every cycle by the plugin.
        func rows(_ kind: String) -> String {
            (1...5).map {
                "$BAR --add item sys.pop.\(kind).\($0) popup.sys --set sys.pop.\(kind).\($0)"
                    + " label=\"…\" label.font=\"\(palette.font)\""
                    + " label.padding_left=10 label.padding_right=10 label.color=\(palette.dim)"
            }.joined(separator: "\n")
        }
        let cpuRows = rows("cpu")
        let memRows = rows("mem")
        return """
            # Two sparkline graphs + a chip, right side. The chip's popup holds
            # the perf panel; a click toggles it.
            # Graphs are their own toggle — the readout can stand alone.
            $BAR --add graph sys.cpu.graph right 32 \\
              --set sys.cpu.graph graph.color=\(accent) graph.fill_color=\(accent)44 \\
                background.height=20 label.drawing=off icon.drawing=off \\
                width=32 update_freq=3 script="$PLUGINS/panewright_system.sh"
            $BAR --add graph sys.mem.graph right 32 \\
              --set sys.mem.graph graph.color=\(palette.dim) graph.fill_color=\(palette.dim)33 \\
                background.height=20 label.drawing=off icon.drawing=off width=32
            $BAR --add item sys right \\
              --set sys label="…" label.font="\(palette.font)" \\
                label.padding_left=8 label.padding_right=8 \\
                background.corner_radius=6 background.height=20 \\
                popup.background.corner_radius=8 popup.background.border_width=1 \\
                popup.background.color=0xf01a1a22 popup.background.border_color=0x44ffffff \\
                popup.horizontal=off popup.align=right popup.y_offset=-6 \\
                script="$PLUGINS/panewright_tooltip.sh" \\
                click_script="$BAR --set sys popup.drawing=toggle" \\
              --subscribe sys mouse.entered mouse.exited
            # Perf-panel rows (updated by the plugin each cycle).
            $BAR --add item sys.pop.load popup.sys \\
              --set sys.pop.load label="…" label.font="\(palette.font)" \\
                label.padding_left=10 label.padding_right=10
            $BAR --add item sys.pop.mem popup.sys \\
              --set sys.pop.mem label="…" label.font="\(palette.font)" \\
                label.padding_left=10 label.padding_right=10
            $BAR --add item sys.pop.hcpu popup.sys \\
              --set sys.pop.hcpu label="TOP · CPU" label.font="\(palette.font)" \\
                label.color=\(accent) label.padding_left=10 label.padding_right=10
            \(cpuRows)
            $BAR --add item sys.pop.hmem popup.sys \\
              --set sys.pop.hmem label="TOP · MEMORY" label.font="\(palette.font)" \\
                label.color=\(accent) label.padding_left=10 label.padding_right=10
            \(memRows)
            $BAR --add item sys.pop.act popup.sys \\
              --set sys.pop.act label="Open Activity Monitor" label.font="\(palette.font)" \\
                label.color=\(palette.dim) label.padding_left=10 label.padding_right=10 \\
                click_script="open -a 'Activity Monitor'; $BAR --set sys popup.drawing=off"
            """
    }

    /// The anchor item: a "+" button on the right that also drives the
    /// plugin, which grows one pill per task leftward from it.
    private static func todoItem(accent: String) -> String {
        """
        $BAR --add item todo right \\
          --set todo update_freq=60 script="$PLUGINS/panewright_todo.sh" \\
            label="+" label.color=\(accent) \\
            label.padding_left=8 label.padding_right=8 \\
            background.corner_radius=6 background.height=20 \\
            background.color=0x22ffffff background.drawing=on \\
            click_script="$SCRIPTS_DIR/todo-add.sh" \\
          --subscribe todo panewright_todo
        """
    }

    /// The keybinding-conflict chip: amber, right-aligned, and absent entirely
    /// when the keymap is clean — a warning that's always there is wallpaper.
    /// Conflicts are known at emit time (they're a property of the config), so
    /// this needs no plugin or polling; regenerating the bar is what refreshes it.
    ///
    /// The count is *rows*, not findings — it has to match what clicking
    /// through actually shows, and it's a count of decisions to make, not of
    /// sentences to read.
    static func conflictsItem(count: Int) -> String {
        guard count > 0 else { return "" }
        return """
            $BAR --add item conflicts right \\
              --set conflicts label="⚠ \(count)" label.color=\(warningColor) \\
                label.padding_left=8 label.padding_right=8 \\
                background.corner_radius=6 background.height=20 \\
                background.color=0x22e0af68 background.drawing=on \\
                click_script="open 'panewright://conflicts'"
            """
    }

    /// Emitted before every other right-side item on purpose. SketchyBar
    /// orders a side by insertion, and the to-do plugin grows its pills
    /// leftward from its anchor — so a chip added after the anchor lands
    /// *between* the "+" and the first task, splitting that group in half.
    /// First means the far right edge: outside every cluster, and the most
    /// visible place for a warning.
    ///
    /// Amber in both themes — it has to read as "look at this" against the
    /// native bar's vibrancy and the technical theme's slate alike.
    static let warningColor = "0xffe0af68"
}
